#!/usr/bin/env python3
"""Regenerate deploy/k8s/rules.yaml (Google Managed Prometheus `Rules` resource) from deploy/prometheus/rules.yml.

    python deploy/sync_rules.py

Keeps the self-managed Prometheus rules (docker compose) and the GKE copy from drifting apart. Needs PyYAML.
"""
from pathlib import Path

import yaml

root = Path(__file__).resolve().parent
groups = yaml.safe_load((root / "prometheus" / "rules.yml").read_text())["groups"]
doc = {
    "apiVersion": "monitoring.googleapis.com/v1",
    "kind": "Rules",
    "metadata": {"name": "inference-slo", "namespace": "model-serving"},
    "spec": {"groups": groups},
}
header = "# GENERATED by deploy/sync_rules.py from deploy/prometheus/rules.yml: edit that file, not this one.\n"
(root / "k8s" / "rules.yaml").write_text(header + yaml.safe_dump(doc, sort_keys=False, width=120))
print("wrote", root / "k8s" / "rules.yaml")
